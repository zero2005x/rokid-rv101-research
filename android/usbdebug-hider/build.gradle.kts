import java.security.MessageDigest
import java.util.Base64

plugins {
    id("com.android.application")
}

// ─────────────────────────────────────────────────────────────────────────────
// At build time the "target app allowlist" can be baked straight into the APK (no reliance on an on-device config file):
//   ./gradlew :usbdebug-hider:assembleDebug -PmaskTargets=com.example.a,com.example.b
// Default "*" = every third-party app (uid >= 10000); system/root/shell always keep the real values.
// ─────────────────────────────────────────────────────────────────────────────
val maskTargets: String =
    (project.findProperty("maskTargets") as String?)?.trim().takeUnless { it.isNullOrEmpty() } ?: "*"

val bakedDir = layout.buildDirectory.dir("generated/baked").get().asFile
bakedDir.mkdirs()
File(bakedDir, "BakedDefaults.java").writeText(
    """
    package com.rokid.rc.usbdebughider;

    /** Generated by build.gradle.kts (-PmaskTargets=...); do not edit by hand. */
    final class BakedDefaults {
        static final String TARGETS = "${maskTargets.replace("\\", "\\\\").replace("\"", "\\\"")}";

        private BakedDefaults() {
        }
    }
    """.trimIndent() + "\n"
)

// ─────────────────────────────────────────────────────────────────────────────
// The native layer (libdebugmask.so) is embedded into the dex as Base64.
//
// Why not rely on the APK path: Android 11+ package visibility stops the target app from resolving our package name
// (PackageManager.NameNotFoundException), and Vector loads modules as in-memory dex, so
// /proc/self/maps does not show the APK path either. Embedded bytes rely on no path discovery at all:
// after injection they are unpacked into "the target app's own cacheDir" and then System.load()-ed.
// Source: src/main/jniLibs/arm64-v8a/libdebugmask.so (produced by deploy/build_debugmask_so.sh)
// ─────────────────────────────────────────────────────────────────────────────
run {
    val soFile = file("src/main/jniLibs/arm64-v8a/libdebugmask.so")
    val outFile = File(bakedDir, "EmbeddedSo.java")
    if (soFile.isFile) {
        val bytes = soFile.readBytes()
        val b64 = Base64.getEncoder().encodeToString(bytes)
        val hash = MessageDigest.getInstance("SHA-256")
            .digest(bytes).joinToString("") { "%02x".format(it) }.substring(0, 16)
        outFile.writeText(
            """
            package com.rokid.rc.usbdebughider;

            /** Generated by build.gradle.kts: the embedded native layer (PLT/GOT hook). Do not edit by hand. */
            final class EmbeddedSo {
                static final String B64 = "$b64";
                static final String HASH = "$hash";
                static final int SIZE = ${bytes.size};

                private EmbeddedSo() {
                }
            }
            """.trimIndent() + "\n"
        )
    } else {
        outFile.writeText(
            """
            package com.rokid.rc.usbdebughider;

            /** libdebugmask.so was not found at build time -> the native layer is disabled automatically (only the Java layer remains). */
            final class EmbeddedSo {
                static final String B64 = "";
                static final String HASH = "none";
                static final int SIZE = 0;

                private EmbeddedSo() {
                }
            }
            """.trimIndent() + "\n"
        )
    }
}

